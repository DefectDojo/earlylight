#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES.txt: the license and NOTICE texts of everything
# compiled into the release binaries (the Go standard library and every module
# linked on any release platform). Run it after changing go.mod; CI fails when
# the committed file is out of date.
#
# usage: scripts/third-party-notices.sh [output]   (default THIRD_PARTY_NOTICES.txt)
set -euo pipefail
cd "$(dirname "$0")/.."
out=${1:-THIRD_PARTY_NOTICES.txt}

# Keep in step with the platforms in .github/workflows/release.yml and the Dockerfile.
platforms="linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64 windows/arm64"

go mod download
mods=$(for p in $platforms; do
  GOOS=${p%/*} GOARCH=${p#*/} CGO_ENABLED=0 go list -deps \
    -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/...
done | sort -u)

# License files first, then NOTICE files, as each module ships them.
texts() {
  local dir=$1 found=0 f
  for f in $(ls "$dir" | LC_ALL=C sort); do
    case $(printf '%s' "$f" | tr '[:upper:]' '[:lower:]') in
      licen[cs]e|licen[cs]e.*|licen[cs]e-*|copying|copying.*|notice|notice.*)
        [ -f "$dir/$f" ] || continue
        printf -- '--- %s ---\n\n' "$f"
        cat "$dir/$f"
        printf '\n'
        found=1 ;;
    esac
  done
  [ "$found" = 1 ] || { echo "no license file in $dir" >&2; exit 1; }
}

{
  echo "Third-party notices for Early Light"
  echo
  echo "Early Light is licensed under the BSD 3-Clause License (see LICENSE)."
  echo "Its release binaries and container image include the software below,"
  echo "each under its own license, reproduced here as its authors ship it."
  echo "This file is generated by scripts/third-party-notices.sh."
  echo
  echo "================================================================"
  echo "The Go standard library"
  echo "================================================================"
  echo
  texts "$(go env GOROOT)"
  printf '%s\n' "$mods" | while read -r path version; do
    [ -n "$path" ] || continue
    dir=$(go list -m -f '{{.Dir}}' "$path")
    echo "================================================================"
    echo "$path $version"
    echo "================================================================"
    echo
    texts "$dir"
  done
} > "$out"

echo "wrote $out ($(printf '%s\n' "$mods" | grep -c .) modules)" >&2
