#!/usr/bin/env python3
"""Build the *sshole fixture images and check each verdict.

usage: python3 parity/sshole.py path/to/earlylight

Needs Docker. The images are built locally from parity/sshole/*.Dockerfile
(vuln first: other cases build on it) and scanned from `docker save`
archives. Writes parity/SSHOLE-RESULTS.md.
"""
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CASES = os.path.join(HERE, "sshole")
ORDER = ["vuln", "fixed", "pwoff", "usepam", "root", "matchonly", "latest", "debian"]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    tool = os.path.abspath(sys.argv[1])
    expected = json.load(open(os.path.join(CASES, "expected.json")))
    rows, failed = [], 0
    with tempfile.TemporaryDirectory() as tmp:
        for case in ORDER:
            tag = "earlylight-parity-sshole:" + case
            subprocess.run(["docker", "build", "-q", "-t", tag, "-f", os.path.join(CASES, case + ".Dockerfile"), CASES],
                           check=True, stdout=subprocess.DEVNULL)
            tar = os.path.join(tmp, case + ".tar")
            subprocess.run(["docker", "save", tag, "-o", tar], check=True)
            out = subprocess.run([tool, "scan", "image", "--detector", "sshole", "--format", "json", "docker-archive:" + tar],
                                 capture_output=True, text=True)
            report = json.loads(out.stdout)
            got = []
            for t in report["targets"]:
                if t.get("error"):
                    got.append(["error", t["error"], "", ""])
                for f in t.get("findings", []):
                    got.append([f["path"], f["kind"], f["verdict"], f.get("severity", "")])
            want = expected[case]
            ok = sorted(got) == sorted(want)
            failed += not ok
            rows.append((case, ok, got, want))
    with open(os.path.join(HERE, "SSHOLE-RESULTS.md"), "w") as f:
        f.write("# *sshole fixture results\n\nGenerated by `parity/sshole.py`.\n\n| Case | Result | Findings |\n| --- | --- | --- |\n")
        for case, ok, got, want in rows:
            cell = "<br>".join(" ".join(x for x in g if x) for g in sorted(got)) or "none"
            f.write(f"| {case} | {'pass' if ok else 'FAIL (want ' + json.dumps(want) + ')'} | {cell} |\n")
        f.write(f"\n{len(rows) - failed}/{len(rows)} cases match.\n")
    print(f"{len(rows) - failed}/{len(rows)} cases match")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
